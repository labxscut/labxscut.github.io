#!/usr/bin/env python3
"""Build _data/member_keywords.yml: a topic cloud per lab member.

Reuses the tokenizer in gen_keywords.py (the SAME phrase list + stopwords that
produce the site-wide cloud), so a member's topics are exactly the site-wide
terms that appear in that member's own paper titles. Deterministic: same
registry -> same output.

Output shape (a list, one entry per member with at least one paper):
  - nick: dhy
    terms:
      - {term: network fusion, count: 3}
      - {term: single cell, count: 2}
      ...

Only terms with count >= 1 are kept; the template sizes them against the
member's own max, so a member with two papers still gets a readable cloud. The
list is capped per member (TOP_N) to keep the card compact.

Usage (WSL):  python3 _generators/gen_member_keywords.py
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

import yaml

from gen_publications import REPO
from gen_keywords import tokenize

DATA = REPO / "_data"
OUT = DATA / "member_keywords.yml"

TOP_N = 12  # terms per member, sized to fit the profile sidebar


def main() -> int:
    people = yaml.safe_load((DATA / "people.yml").read_text(encoding="utf-8"))
    people = people if isinstance(people, list) else (
        people.get("people") if isinstance(people, dict) else [])

    rows = []
    for person in people:
        nick = person.get("nick")
        if not nick:
            continue
        papers = person.get("papers") or []
        if not papers:
            continue
        counts: Counter[str] = Counter()
        for paper in papers:
            title = paper.get("title")
            if not title:
                continue
            # one count per distinct term per paper, mirroring the site-wide
            # slugs logic: a term repeated inside one title still means one paper
            for term in set(tokenize(title)):
                counts[term] += 1
        if not counts:
            continue
        terms = [{"term": t, "count": c}
                 for t, c in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))]
        rows.append({"nick": nick, "terms": terms[:TOP_N]})

    rows.sort(key=lambda r: r["nick"])

    HEADER = (
        "# Topic cloud per lab member, generated by _generators/gen_member_keywords.py\n"
        "# from the member's own paper titles using the SAME tokenizer as the\n"
        "# site-wide cloud (_data/keywords.yml). Do not edit by hand.\n"
    )
    OUT.write_text(HEADER + yaml.safe_dump(rows, allow_unicode=True, sort_keys=False),
                   encoding="utf-8")
    print(f"member_keywords: {len(rows)} members")
    return 0


if __name__ == "__main__":
    sys.exit(main())
